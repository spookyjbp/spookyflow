#!/usr/bin/env python3
"""Generate src/core/font_data.c: two RLE-compressed alpha glyph atlases.

  FONT_MAIN : DejaVu Sans, 40 px, ASCII + Latin-1 + a few symbols (UI text)
  FONT_BIG  : DejaVu Sans Bold, 128 px, '#', A-Z and the letters of the
              wordmark (letter-jump overlay + loading screen wordmark)

Atlas pixels are 8-bit coverage (alpha). Runtime expands them into a white
A8R8G8B8 texture. RLE format (PackBits-like):
  byte n < 128  : the next byte repeats n+1 times
  byte n >= 128 : (n-127) literal bytes follow
Usage: python3 tools/gen_font.py  (run from the project root)
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEJAVU = "/usr/share/fonts/truetype/dejavu/"

def rle(data):
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        # run?
        j = i
        while j < n and j - i < 128 and data[j] == data[i]:
            j += 1
        run = j - i
        if run >= 3:
            out.append(run - 1)
            out.append(data[i])
            i = j
            continue
        # literal: until a run of >=3 starts or 128 bytes
        j = i
        while j < n and j - i < 128:
            if j + 2 < n and data[j] == data[j + 1] == data[j + 2]:
                break
            j += 1
        if j == i:
            j = i + 1
        out.append(127 + (j - i))
        out.extend(data[i:j])
        i = j
    return bytes(out)

def unrle(buf, size):
    out = bytearray()
    i = 0
    while i < len(buf):
        n = buf[i]; i += 1
        if n < 128:
            out.extend([buf[i]] * (n + 1)); i += 1
        else:
            k = n - 127
            out.extend(buf[i:i + k]); i += k
    assert len(out) == size, (len(out), size)
    return bytes(out)

def build(name, path, px, codepoints, atlas_w):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    cap_bbox = font.getbbox("H", anchor="ls")
    cap_h = -cap_bbox[1]
    glyphs = []
    for cp in codepoints:
        ch = chr(cp)
        adv = font.getlength(ch)
        bb = font.getbbox(ch, anchor="ls")  # relative to baseline origin
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        glyphs.append([cp, bb[0], bb[1], max(w, 0), max(h, 0), adv])
    pad = 2
    x = y = pad
    row_h = 0
    for g in glyphs:
        w, h = g[3], g[4]
        if x + w + pad > atlas_w:
            x = pad
            y += row_h + pad
            row_h = 0
        g.append(x); g.append(y)
        x += w + pad
        row_h = max(row_h, h)
    atlas_h = 1
    need = y + row_h + pad
    while atlas_h < need:
        atlas_h *= 2
    img = Image.new("L", (atlas_w, atlas_h), 0)
    dr = ImageDraw.Draw(img)
    for g in glyphs:
        cp, bx, by, w, h, adv, gx, gy = g
        if w and h:
            dr.text((gx - bx, gy - by), chr(cp), font=font, fill=255, anchor="ls")
    raw = img.tobytes()
    comp = rle(raw)
    assert unrle(comp, len(raw)) == raw
    img.save(os.path.join(ROOT, "tools", "atlas_%s.png" % name.lower()))
    return dict(name=name, px=px, ascent=ascent, descent=descent, cap=cap_h,
                w=atlas_w, h=atlas_h, glyphs=glyphs, rle=comp)

def emit(fonts, out_path):
    L = []
    L.append("/* GENERATED by tools/gen_font.py - do not edit. */")
    L.append("/* Glyphs rendered from DejaVu fonts (Bitstream Vera derived, free license). */")
    L.append('#include "font.h"')
    L.append("")
    for f in fonts:
        n = f["name"].lower()
        L.append("static const FontGlyph %s_glyphs[%d] = {" % (n, len(f["glyphs"])))
        for cp, bx, by, w, h, adv, gx, gy in f["glyphs"]:
            L.append("  {0x%04X, %d, %d, %d, %d, %d, %d, %.2ff}," % (cp, gx, gy, w, h, bx, by, adv))
        L.append("};")
        data = f["rle"]
        L.append("static const unsigned char %s_rle[%d] = {" % (n, len(data)))
        for i in range(0, len(data), 24):
            L.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        L.append("};")
        L.append("const Font %s = {" % f["name"].lower().replace("font_", "g_font_"))
        L.append("  %s_glyphs, %d, %d, %d, %d, %d, %d, %d, %s_rle, %d" % (
            n, len(f["glyphs"]), f["px"], f["ascent"], f["descent"], f["cap"],
            f["w"], f["h"], n, len(data)))
        L.append("};")
        L.append("")
    with open(out_path, "w") as fp:
        fp.write("\n".join(L))

def main():
    main_cps = list(range(32, 127)) + list(range(0xA0, 0x100)) + \
        [0x2026, 0x2039, 0x203A, 0x2022, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D]
    big_cps = sorted(set(ord(c) for c in "#ABCDEFGHIJKLMNOPQRSTUVWXYZspookyflw"))
    f1 = build("FONT_MAIN", DEJAVU + "DejaVuSans.ttf", 40, sorted(set(main_cps)), 1024)
    f2 = build("FONT_BIG", DEJAVU + "DejaVuSans-Bold.ttf", 128, big_cps, 1024)
    emit([f1, f2], os.path.join(ROOT, "src", "core", "font_data.c"))
    for f in (f1, f2):
        print("%s: %dx%d atlas, %d glyphs, rle %d bytes (raw %d)" % (
            f["name"], f["w"], f["h"], len(f["glyphs"]), len(f["rle"]), f["w"] * f["h"]))

if __name__ == "__main__":
    sys.exit(main())
