#!/usr/bin/env python3
"""gen_gamedb.py - build src/core/gamedb_data.c: title ID -> release year.

Source: GameDB by Niema Moshiri (https://github.com/niemasd/GameDB-PSX,
GameDB-PS2, GameDB-PS3; GPL-3.0), compiled from Redump, GameFAQs, PlayStation
Datacenter and others. Only the serial and the year of its release date are
kept (the earliest year if a serial is listed more than once).

usage: python3 tools/gen_gamedb.py <dir containing GameDB-PSX, GameDB-PS2, GameDB-PS3>
"""
import os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else '.'
years = {}
for repo in ('GameDB-PSX', 'GameDB-PS2', 'GameDB-PS3'):
    gdir = os.path.join(root, repo, 'games')
    for serial in os.listdir(gdir):
        f = os.path.join(gdir, serial, 'release_date.txt')
        if not os.path.isfile(f):
            continue
        m = re.match(r'\s*(\d{4})', open(f, encoding='utf-8', errors='replace').read())
        if not m:
            continue
        y = int(m.group(1))
        sid = re.sub(r'[^A-Z0-9]', '', serial.upper())
        if not re.fullmatch(r'[A-Z]{4}\d{5}', sid) or not (1994 <= y <= 1994 + 255):
            continue
        years[sid] = min(y, years.get(sid, 9999))

prefixes = sorted({k[:4] for k in years})
pidx = {p: i for i, p in enumerate(prefixes)}
entries = sorted(((pidx[k[:4]] << 17) | int(k[4:]), years[k] - 1994) for k in years)

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'core', 'gamedb_data.c')
with open(out, 'w') as f:
    f.write('/* gamedb_data.c - GENERATED by tools/gen_gamedb.py, do not edit.\n')
    f.write(' * Title ID -> release year, from GameDB by Niema Moshiri (GPL-3.0):\n')
    f.write(' * https://github.com/niemasd/GameDB-PSX, -PS2, -PS3. */\n')
    f.write('#include "gamedb.h"\n\n')
    f.write('const char g_gamedb_prefix[][5] = {\n')
    for i in range(0, len(prefixes), 12):
        f.write('    ' + ', '.join('"%s"' % p for p in prefixes[i:i + 12]) + ',\n')
    f.write('};\nconst int g_gamedb_nprefix = %d;\n\n' % len(prefixes))
    f.write('/* (prefix index << 17) | number, sorted */\nconst uint32_t g_gamedb_key[] = {\n')
    for i in range(0, len(entries), 10):
        f.write('    ' + ', '.join('0x%07X' % k for k, _ in entries[i:i + 10]) + ',\n')
    f.write('};\n/* year - 1994 */\nconst uint8_t g_gamedb_year[] = {\n')
    for i in range(0, len(entries), 24):
        f.write('    ' + ','.join('%d' % y for _, y in entries[i:i + 24]) + ',\n')
    f.write('};\nconst int g_gamedb_count = %d;\n' % len(entries))
print('%d serials, %d prefixes -> %s' % (len(entries), len(prefixes), out))
