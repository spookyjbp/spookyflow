#!/usr/bin/env python3
"""gen_stage.py - embed the Stage background into src/core/stage_data.c.

art/stage.jpg         1280x720 base scene (brightness)
art/stage_rib.jpg     light ribbons (brightness)
art/stage_fx.png      brightness atlas (flares, mist, particles) + art/stage_fx.json rects
art/stage_shapes.png  RGBA 1024x896: 4 shapes x 2 angles x (glass body, white-hot edges)
The PS3 decodes them at startup (jpgLoadFromBuffer / pngLoadFromBuffer).
"""
import os, json
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
out = os.path.join(root, 'src', 'core', 'stage_data.c')
def arr(name, data):
    lines = ['const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join('%d' % b for b in data[i:i + 20]) + ',')
    lines.append('};')
    lines.append('const unsigned int %s_size = %d;' % (name, len(data)))
    return '\n'.join(lines) + '\n'
rd = lambda n: open(os.path.join(root, 'art', n), 'rb').read()
fx = json.load(open(os.path.join(root, 'art', 'stage_fx.json')))
order = ['glow', 'line', 'mist', 'dots']
with open(out, 'w') as f:
    f.write('/* stage_data.c - GENERATED by tools/gen_stage.py from art/stage*.  Do not edit. */\n')
    f.write('#include "stage.h"\n\n')
    f.write('const int g_stage_fx_size[2] = { %d, %d };\n' % tuple(fx['size']))
    f.write('const int g_stage_fx_rect[STAGE_FX_COUNT][4] = {\n')
    for n in order: f.write('    { %d, %d, %d, %d },   /* %s */\n' % (tuple(fx['rects'][n]) + (n,)))
    f.write('};\n\n')
    f.write(arr('g_stage_jpg', rd('stage.jpg')))
    f.write(arr('g_stage_rib_jpg', rd('stage_rib.jpg')))
    f.write(arr('g_stage_glow_jpg', rd('stage_glow.jpg')))
    f.write(arr('g_stage_fx_png', rd('stage_fx.png')))
    f.write(arr('g_stage_shapes_png', rd('stage_shapes.png')))
print('->', out)
