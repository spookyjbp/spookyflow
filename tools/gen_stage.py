#!/usr/bin/env python3
"""gen_stage.py - embed the "Stage" background into src/core/stage_data.c.

art/stage.jpg        1280x720 background (the floating shapes removed)
art/stage_shapes.png 512x128 RGBA: cross, circle, triangle, square (128 px cells)
The PS3 decodes them at startup (jpgLoadFromBuffer / pngLoadFromBuffer).
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..')
out = os.path.join(root, 'src', 'core', 'stage_data.c')
def arr(name, data):
    lines = ['const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 20):
        lines.append('    ' + ','.join('%d' % b for b in data[i:i + 20]) + ',')
    lines.append('};')
    lines.append('const unsigned int %s_size = %d;' % (name, len(data)))
    return '\n'.join(lines) + '\n'
jpg = open(os.path.join(root, 'art', 'stage.jpg'), 'rb').read()
png = open(os.path.join(root, 'art', 'stage_shapes.png'), 'rb').read()
with open(out, 'w') as f:
    f.write('/* stage_data.c - GENERATED by tools/gen_stage.py from art/stage.jpg and art/stage_shapes.png. */\n')
    f.write('#include "stage.h"\n\n')
    f.write(arr('g_stage_jpg', jpg))
    f.write(arr('g_stage_shapes_png', png))
print(len(jpg), len(png), '->', out)
