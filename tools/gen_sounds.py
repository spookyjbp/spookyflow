#!/usr/bin/env python3
"""Make the built-in UI sounds (src/core/sounds_data.c) from a folder of WAVs
named like the override files: move.wav, tab.wav, open.wav, close.wav,
change.wav, confirm.wav.

    python3 tools/gen_sounds.py <folder with the .wav files>

Each WAV (PCM 8/16-bit, mono or stereo, any rate) is converted the same way
spookyflow converts an override file on the PS3 (sound.c): channels averaged
to mono, linear resampling to 48 kHz, at most SND_MAX_SECONDS long; stored
as 16-bit samples. Files in /dev_hdd0/tmp/spookyflow/sounds/ still replace
these at start-up."""
import os
import struct
import sys
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["move", "tab", "open", "close", "change", "confirm"]   # SoundId order (sound.h)
RATE = 48000
MAX_SECONDS = 3


def convert(path):
    w = wave.open(path, "rb")
    ch, bits, rate, n = w.getnchannels(), w.getsampwidth() * 8, w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    w.close()
    if bits == 16:
        vals = struct.unpack("<%dh" % (len(raw) // 2), raw)
        samp = [v / 32768.0 for v in vals]
    elif bits == 8:
        samp = [(b - 128) / 128.0 for b in raw]
    else:
        raise SystemExit("%s: %d-bit WAVs are not supported" % (path, bits))
    frames = len(samp) // ch
    mono = [sum(samp[f * ch:(f + 1) * ch]) / ch for f in range(frames)]
    out_len = min(int(frames * RATE / rate), MAX_SECONDS * RATE)
    out = []
    for i in range(out_len):
        src = i * rate / RATE
        f0 = int(src)
        f1 = f0 + 1 if f0 + 1 < frames else f0
        fr = src - f0
        v = mono[f0] + (mono[f1] - mono[f0]) * fr
        out.append(max(-32768, min(32767, int(round(v * 32768.0)))))
    return out


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    folder = sys.argv[1]
    data = []
    for n in NAMES:
        p = os.path.join(folder, n + ".wav")
        if not os.path.exists(p):
            raise SystemExit("missing " + p)
        data.append(convert(p))
        print("%-8s %6d samples (%.3f s)" % (n, len(data[-1]), len(data[-1]) / RATE))
    L = ["/* sounds_data.c - GENERATED by tools/gen_sounds.py from the UI sound WAVs. Do not edit.",
         " * 48 kHz mono 16-bit, in SoundId order (sound.h). */",
         '#include "sound.h"', ""]
    for n, d in zip(NAMES, data):
        L.append("static const short k_%s[%d] = {" % (n, len(d)))
        for i in range(0, len(d), 20):
            L.append("  " + ",".join(str(v) for v in d[i:i + 20]) + ",")
        L.append("};")
    L.append("const short *const g_sound_builtin[SND_COUNT] = { %s };" % ", ".join("k_" + n for n in NAMES))
    L.append("const int g_sound_builtin_len[SND_COUNT] = { %s };" % ", ".join(str(len(d)) for d in data))
    out = os.path.join(ROOT, "src", "core", "sounds_data.c")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
