#define MUS_DIR "/dev_hdd0/tmp/spookyflow/music"

static int mus_list(void *ctx, const char *dir, FsEntry *out, int max)
{
    static const struct { const char *dir, *name; int is_dir; } k[] = {
        { MUS_DIR, "b tone.mp3", 0 }, { MUS_DIR, "A Song.WAV", 0 }, { MUS_DIR, "cover.jpg", 0 },
        { MUS_DIR, ".hidden.mp3", 0 }, { MUS_DIR, "Album", 1 }, { MUS_DIR, "notes.txt", 0 },
        { MUS_DIR "/Album", "01 tagged.mp3", 0 }, { MUS_DIR "/Album", "Deeper", 1 },
        { MUS_DIR "/Album/Deeper", "ignored.mp3", 0 },
    };
    int i, n = 0, found = 0;
    (void)ctx;
    for (i = 0; i < (int)(sizeof(k) / sizeof(k[0])); i++) {
        if (strcmp(k[i].dir, dir) != 0) continue;
        found = 1;
        if (n >= max) break;
        sf_strlcpy(out[n].name, k[i].name, FS_NAME_MAX);
        out[n].is_dir = k[i].is_dir;
        out[n].size = 0;
        n++;
    }
    return found ? n : -1;
}

/* decode one whole track; returns its frames at 48 kHz and counts sign changes of the left channel */
static int mus_play_one(const char *path, int *crossings, float *peak)
{
    const char *p[1];
    int steps = 0, gen0, frames = 0, prev_sign = 0;
    float buf[512 * 2];
    p[0] = path;
    music_reset();
    music_set_gap(0.0f);
    music_set_playlist(p, 1);
    music_set_volume(1.0f);
    music_set_playing(1);
    *crossings = 0; *peak = 0.0f;
    gen0 = music_decoder_current(NULL, 0);
    /* decode until the 2nd start of the (only) track; drain the ring as we go */
    while (steps++ < 20000) {
        uint32_t before = music_buffered();
        int gen;
        music_decode_step();
        gen = music_decoder_current(NULL, 0);
        if (gen >= gen0 + 2) { frames += (int)before; break; }   /* frames of the first play, already counted below */
        while (music_buffered() > 512 && gen == gen0 + 1) {
            int i;
            memset(buf, 0, sizeof(buf));
            music_mix(buf, 512);
            frames += 512;
            for (i = 0; i < 512; i++) {
                float v = buf[i * 2];
                int s = v > 0.01f ? 1 : (v < -0.01f ? -1 : 0);
                if (s && prev_sign && s != prev_sign) (*crossings)++;
                if (s) prev_sign = s;
                if (fabsf(v) > *peak) *peak = fabsf(v);
            }
        }
    }
    music_set_playing(0);
    return frames;
}

